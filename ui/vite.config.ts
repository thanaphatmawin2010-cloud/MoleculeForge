function filesUnder(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? filesUnder(path) : [path];
  });
}
const posix = (path: string) => path.split(sep).join("/");

/**
 * The service worker: on first visit it caches every file of the build (versioned by a hash of
 * their contents) and then serves the app from that cache, so the trial keeps working offline. A
 * new deployment takes over once every tab of the old one is closed. Same-origin GET only.
 */
function serviceWorker(version: string, files: string[]): string {
  return `/* MoleculeForge Lite offline cache. Generated by ui/vite.config.ts at build time. */
const CACHE = "moleculeforge-lite-${version}";
const FILES = ${JSON.stringify(["./", ...files])};
self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((key) => key.startsWith("moleculeforge-lite-") && key !== CACHE).map((key) => caches.delete(key)))),
  );
});
self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      // Files are immutable per version, so Vary headers (e.g. Origin on module scripts) are ignored.
      const options = { ignoreSearch: true, ignoreVary: true };
      const hit = (await cache.match(request, options)) || (request.mode === "navigate" ? await cache.match("./", options) : undefined);
      return hit || fetch(request);
    }),
  );
});
`;
}

function liteAssets(): Plugin {
  let outDir = "";
  let building = false;
  return {
    name: "moleculeforge-lite-assets",
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
      building = config.command === "build";
    },
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const path = (req.url ?? "").split("?")[0]!.replace(/^\/+/, "");
        if (path === "manifest.webmanifest") {
          res.setHeader("Content-Type", "application/manifest+json");
          res.end(JSON.stringify(MANIFEST));
          return;
        }
        const file = LITE_FILES[path] ?? (path.startsWith("icons/") && existsSync(join(LITE_PUBLIC, path)) ? join(LITE_PUBLIC, path) : undefined);
        if (!file) return next();
        res.setHeader("Content-Type", file.endsWith(".png") ? "image/png" : file.endsWith(".txt") ? "text/plain; charset=utf-8" : "application/json; charset=utf-8");
        res.end(readFileSync(file));
      });
    },
    generateBundle() {
      for (const [fileName, source] of Object.entries(LITE_FILES)) this.emitFile({ type: "asset", fileName, source: readFileSync(source) });
      for (const path of filesUnder(LITE_PUBLIC)) this.emitFile({ type: "asset", fileName: posix(relative(LITE_PUBLIC, path)), source: readFileSync(path) });
      this.emitFile({ type: "asset", fileName: "manifest.webmanifest", source: JSON.stringify(MANIFEST, null, 2) + "\n" });
    },
    closeBundle() {
      if (!building) return;
      // Every file except the worker itself and legacy .woff fonts (browsers that run WebAssembly use .woff2).
      const files = filesUnder(outDir).map((path) => posix(relative(outDir, path))).filter((name) => name !== "sw.js" && !name.endsWith(".woff")).sort();
      const hash = createHash("sha256");
      for (const name of files) hash.update(name).update(readFileSync(join(outDir, name)));
      writeFileSync(join(outDir, "sw.js"), serviceWorker(hash.digest("hex").slice(0, 16), files));
    },
    transformIndexHtml: (html) => ({
      html: html.replace("<title>MoleculeForge</title>", "<title>MoleculeForge Lite</title>"),
      tags: [
        { tag: "meta", attrs: { name: "description", content: MANIFEST.description }, injectTo: "head" },
        { tag: "meta", attrs: { name: "theme-color", content: MANIFEST.theme_color }, injectTo: "head" },
        { tag: "link", attrs: { rel: "manifest", href: "manifest.webmanifest" }, injectTo: "head" },
        { tag: "link", attrs: { rel: "apple-touch-icon", href: "icons/icon-192.png" }, injectTo: "head" },
      ],
    }),
  };
}

// The UI is always served from the bundle: no CDN, no remote assets (spec P3/X3).
export default defineConfig(({ mode, command }) => {
  const lite = mode === "lite";
  return {
    // Lite is served from a sub-path (GitHub Pages) or the Android asset loader: relative URLs.
    base: lite && command === "build" ? "./" : "/",
    plugins: [
      react(),
      contentSecurityPolicy(lite ? "lite" : "desktop", !lite && (mode !== "production" || process.env.VITE_ENABLE_BRIDGE === "1")),
      ...(lite ? [liteAssets()] : []),
    ],
    resolve: {
      alias: [
        // Desktop builds (and unit tests) get a stub, so the WebAssembly engine never enters them.
        ...(lite ? [] : [{ find: /^@\/lite\/transport$/, replacement: here("./src/lite/transport.desktop.ts") }]),
        { find: "@", replacement: here("./src") },
      ],
    },
    clearScreen: false,
    // Scan only the app's own entry for dependencies (not dist-lite/ or test reports in this folder).
    optimizeDeps: { entries: ["index.html"] },
    server: { host: "127.0.0.1", port: lite ? 5174 : 5173, strictPort: true },
    worker: { format: "es" },
    build: {
      target: "es2022",
      outDir: lite ? "dist-lite" : "dist",
      sourcemap: false,
      chunkSizeWarningLimit: 1500,
      rollupOptions: {
        output: {
          manualChunks: {
            three: ["three"],
            react: ["react", "react-dom"],
            i18n: ["i18next", "react-i18next", "i18next-icu", "intl-messageformat"],
          },
        },
      },
    },
    test: {
      // Test files live in ../tests/unit/ui (repository layout); resolve their bare imports from here.
      alias: { zod: here("./node_modules/zod") },
      // Transform (rather than externalise) the ICU stack so Node's CommonJS interop matches the app bundle.
      server: { deps: { inline: ["i18next-icu", "intl-messageformat"] } },
      environment: "jsdom",
      setupFiles: ["./vitest.setup.ts"],
      include: ["src/**/*.test.{ts,tsx}", "../tests/unit/ui/**/*.test.{ts,tsx}", "../tests/unit/lite/**/*.test.ts"],
      css: false,
    },
  };
}) as never;
