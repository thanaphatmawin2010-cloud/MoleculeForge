#!/usr/bin/env python3
"""Generate ui/src/lite/engine/tables.generated.ts from the desktop engine's RDKit.

MoleculeForge Lite (the browser and Android builds) runs RDKit's official WebAssembly build, which
does not expose RDKit's periodic table, QED or Gasteiger parameters. This script copies those
tables from the RDKit release the desktop sidecar uses, so both engines apply the same valence
rules, drug-likeness model and partial-charge parameters. Run it after upgrading RDKit:

    compute/.venv/bin/python scripts/gen_lite_tables.py

The Gasteiger parameters are RDKit's (Code/GraphMol/PartialCharges/GasteigerParams.cpp, BSD-3-Clause),
reproduced at the version pinned in compute/pyproject.toml.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import rdkit
from rdkit import Chem
from rdkit.Chem import QED

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "ui" / "src" / "lite" / "engine" / "tables.generated.ts"

# RDKit's GasteigerParams.cpp (defaultParamData + additionalParamData), release pinned above.
GASTEIGER = """
H * 7.17 6.24 -0.56
C sp3 7.98 9.18 1.88
C sp2 8.79 9.32 1.51
C sp 10.39 9.45 0.73
N sp3 11.54 10.82 1.36
N sp2 12.87 11.15 0.85
N sp 15.68 11.7 -0.27
O sp3 14.18 12.92 1.39
O sp2 17.07 13.79 0.47
F sp3 14.66 13.85 2.31
Cl sp3 11.00 9.69 1.35
Br sp3 10.08 8.47 1.16
I sp3 9.9 7.96 0.96
S sp3 10.14 9.13 1.38
S so 10.14 9.13 1.38
S so2 12.00 10.81 1.20
S sp2 10.88 9.49 1.33
P sp3 8.90 8.24 0.96
X * 0.00 0.00 0.00
P sp2 9.665 8.530 0.735
Si sp3 7.300 6.567 0.657
Si sp2 7.905 6.748 0.443
Si sp 9.065 7.027 -0.002
B sp3 5.980 6.820 1.605
B sp2 6.420 6.807 1.322
Be sp3 3.845 6.755 3.165
Be sp2 4.005 6.725 3.035
Mg sp2 3.565 5.572 2.197
Mg sp3 3.300 5.587 2.447
Mg sp 4.040 5.472 1.823
Al sp3 5.375 4.953 0.867
Al sp2 5.795 5.020 0.695
"""


def main() -> int:
    pt = Chem.GetPeriodicTable()
    symbols = [pt.GetElementSymbol(z) for z in range(0, 119)]
    valences = [list(pt.GetValenceList(z)) for z in range(0, 119)]
    default_valence = [pt.GetDefaultValence(z) for z in range(0, 119)]
    outer = [pt.GetNOuterElecs(z) for z in range(0, 119)]
    # Mass numbers RDKit knows for each element (validation flags any other isotope).
    isotopes = [[iso for iso in range(1, 351) if z and pt.GetMassForIsotope(z, iso) > 0.0] for z in range(0, 119)]
    gasteiger = {}
    for line in GASTEIGER.strip().splitlines():
        el, mode, a, b, c = line.split()
        gasteiger[f"{el}|{mode}"] = [float(a), float(b), float(c)]
    qed = {
        "acceptors": list(QED.AcceptorSmarts),
        "alerts": list(QED.StructuralAlertSmarts),
        "aliphaticRings": "[$([A;R][!a])]",
        "ads": {name: list(p) for name, p in QED.adsParameters.items()},
        "weightsMean": list(QED.WEIGHT_MEAN),
        "names": list(QED.QEDproperties._fields),
    }
    body = [
        "// Generated by scripts/gen_lite_tables.py from RDKit " + rdkit.__version__ + ". Do not edit.",
        "/* eslint-disable */",
        f"export const RDKIT_VERSION = {json.dumps(rdkit.__version__)};",
        f"export const SYMBOLS: string[] = {json.dumps(symbols)};",
        f"export const VALENCE_LISTS: number[][] = {json.dumps(valences)};",
        f"export const DEFAULT_VALENCE: number[] = {json.dumps(default_valence)};",
        f"export const OUTER_ELECTRONS: number[] = {json.dumps(outer)};",
        f"export const KNOWN_ISOTOPES: number[][] = {json.dumps(isotopes)};",
        f"export const GASTEIGER_PARAMS: Record<string, [number, number, number]> = {json.dumps(gasteiger)};",
        f"export const QED_PARAMS = {json.dumps(qed, ensure_ascii=False)} as const;",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(body), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} (RDKit {rdkit.__version__})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
